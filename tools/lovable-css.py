"""Lovable's screen designs (tools/lovable-screens/*.html) -> public/sop-screens.css.

Each design is a self-contained page drawn for real screens (390 px phones,
1366 px computers, switching at 900 px). The game draws on a fixed artboard
(600 wide on phones, 1920 wide on computers) that is scaled to fit, so every
px is multiplied by --k (600/390 on phones, 1920/1366 on computers), the
900 px media query becomes "not a phone" (body:not(.sop-portrait)), and each
screen's rules are scoped under its own class (.lv-council, .lv-dec, ...).
Run: python3 tools/lovable-css.py"""
import re, pathlib
ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "tools" / "lovable-screens"
SCREENS = [("lv-council", "screen-council-decision.html"), ("lv-dec", "screen-decision-result.html"), ("lv-ey", "screen-endyear.html"), ("lv-desk", "screen-desk.html")]

def px(v):
    return re.sub(r"(-?\d*\.?\d+)px", lambda m: "0" if float(m.group(1)) == 0 else "calc(%spx*var(--k))" % m.group(1), v).replace("100vh", "100%").replace("url(art/compound.webp)", "url(art/compound/compound-full.webp)")

def rules(css):
    out, i = [], 0
    while i < len(css):
        j = css.find("{", i)
        if j < 0: break
        sel = css[i:j].strip()
        if sel.startswith("@media"):
            depth, k = 1, j + 1
            while depth: depth += {"{": 1, "}": -1}.get(css[k], 0); k += 1
            out.append(("@media", sel, rules(css[j + 1:k - 1])))
            i = k
        else:
            k = css.find("}", j)
            out.append((sel, css[j + 1:k].strip()))
            i = k + 1
    return out

def scope(sel, root, desk):
    parts = []
    for s in sel.split(","):
        s = s.strip()
        if s in (":root", "body", "html,body", "html"): s = ""
        elif s == "*": s = "*"
        elif s in ("img", "button"): pass
        pre = ("body:not(.sop-portrait) " if desk else "") + "." + root
        parts.append(pre if s == "" else (pre + " " + s))
    return ",".join(dict.fromkeys(parts))

def convert(root, html):
    css = re.search(r"<style>(.*?)</style>", html, re.S).group(1)
    css = re.sub(r"/\*.*?\*/", "", css, flags=re.S)
    lines = []
    def emit(rs, desk=False):
        for r in rs:
            if r[0] == "@media":
                if "min-width:900px" in r[1].replace(" ", ""): emit(r[2], True)
                continue
            sel, body = r
            if sel in ("html,body",) and "height" in body: continue
            if sel == "body" and "background:#000" in body.replace(" ", ""): continue
            lines.append(scope(sel, root, desk) + "{" + px(body) + "}")
    emit(rules(css))
    return "\n".join(lines)

out = ["/* Generated by tools/lovable-css.py from Lovable's screen designs. Do not edit by hand. */",
       ".lv{--k:1.4056;font-size:calc(15px*var(--k))}", "body.sop-portrait .lv{--k:1.5385}"]
for root, f in SCREENS:
    out.append("/* " + f + " */")
    out.append(convert(root, (SRC / f).read_text()))
(ROOT / "public" / "sop-screens.css").write_text("\n".join(out) + "\n")
print("wrote public/sop-screens.css", sum(len(x) for x in out), "bytes")
